#!/usr/bin/env python3
"""Generate src/semantic/bios_calls.c from the retail BIOS stubs.

Scans config/US/funcs.tsv for `li t2,0xA0|B0|C0; jr t2; li t1,n` stubs and
the two critical-section syscall stubs, names them from the BIOS call table
and records the names in config/US/names.tsv (source=bios rows replaced).
"""
import csv, json
from pathlib import Path
from mips import Image

ROOT = Path(__file__).resolve().parents[1]

NAMES = {
    ('A0', 0x13): 'setjmp', ('A0', 0x15): 'strcat', ('A0', 0x17): 'strcmp', ('A0', 0x18): 'strncmp',
    ('A0', 0x19): 'strcpy', ('A0', 0x1B): 'strlen', ('A0', 0x24): 'strstr', ('A0', 0x28): 'bzero',
    ('A0', 0x2A): 'memcpy', ('A0', 0x2B): 'memset', ('A0', 0x2E): 'memchr', ('A0', 0x2F): 'rand',
    ('A0', 0x30): 'srand', ('A0', 0x34): 'free', ('A0', 0x39): 'InitHeap', ('A0', 0x3F): 'printf',
    ('A0', 0x44): 'FlushCache', ('A0', 0x49): 'GPU_cw', ('A0', 0x70): '_bu_init', ('A0', 0x72): '_96_remove',
    ('A0', 0xAB): '_card_info', ('A0', 0xAC): '_card_load',
    ('B0', 0x07): 'DeliverEvent', ('B0', 0x08): 'OpenEvent', ('B0', 0x09): 'CloseEvent', ('B0', 0x0A): 'WaitEvent',
    ('B0', 0x0B): 'TestEvent', ('B0', 0x0C): 'EnableEvent', ('B0', 0x0D): 'DisableEvent', ('B0', 0x12): 'InitPAD2',
    ('B0', 0x13): 'StartPAD2', ('B0', 0x14): 'StopPAD2', ('B0', 0x15): 'PAD_init', ('B0', 0x17): 'ReturnFromException',
    ('B0', 0x18): 'ResetEntryInt', ('B0', 0x19): 'HookEntryInt', ('B0', 0x32): 'open', ('B0', 0x33): 'lseek',
    ('B0', 0x34): 'read', ('B0', 0x35): 'write', ('B0', 0x36): 'close', ('B0', 0x38): 'exit', ('B0', 0x3F): 'puts',
    ('B0', 0x41): 'format', ('B0', 0x42): 'firstfile', ('B0', 0x43): 'nextfile', ('B0', 0x45): 'erase',
    ('B0', 0x47): 'AddDrv', ('B0', 0x48): 'DelDrv', ('B0', 0x4A): 'InitCARD', ('B0', 0x4B): 'StartCARD',
    ('B0', 0x4C): 'StopCARD', ('B0', 0x4E): '_card_write', ('B0', 0x50): '_new_card', ('B0', 0x5B): 'ChangeClearPAD',
    ('C0', 0x02): 'SysEnqIntRP', ('C0', 0x03): 'SysDeqIntRP', ('C0', 0x0A): 'ChangeClearRCnt',
}

HEADER = r'''/* Genuine PSX BIOS jump-table and syscall interfaces: a retained SDK
 * boundary, following TM2-Release bios_extra.c. Each entry is emitted at its
 * retail address so the BIOS sees the caller frame, arguments and RA
 * unchanged. No game algorithm is replaced by assembly here. Names follow
 * the BIOS call numbers; a repeated stub for the same call gets a suffix.
 * Generated by tools/gen_bios.py. */
#ifndef __mips__
#error These interfaces require the real PSX BIOS.
#endif

#define BIOS_TABLE_ENTRY(name,va,table,number) \
    __asm__(".section .text_" #va ",\"ax\",@progbits\n.align 2\n" \
            ".globl " #name "\n.type " #name ",@function\n" \
            #name ":\n.set noreorder\n" \
            "addiu $10,$0," #table "\njr $10\naddiu $9,$0," #number "\nnop\n" \
            ".set reorder\n.size " #name ",.-" #name "\n")
#define BIOS_SYSCALL_ENTRY(name,va,selector) \
    __asm__(".section .text_" #va ",\"ax\",@progbits\n.align 2\n" \
            ".globl " #name "\n.type " #name ",@function\n" \
            #name ":\n.set noreorder\n" \
            "addiu $4,$0," #selector "\nsyscall\njr $31\nnop\n" \
            ".set reorder\n.size " #name ",.-" #name "\n")

'''


def main():
    img = Image((ROOT / 'bin/SLUS_006.43').read_bytes())
    lines, funcs, seen = [HEADER.rstrip('\n'), ''], {}, {}
    for r in csv.DictReader((ROOT / 'config/US/funcs.tsv').open(), delimiter='\t'):
        va = int(r['va'], 16)
        w = [img.word(va + 4 * i) for i in range(4)]
        if w[0] >> 16 == 0x240A and w[1] == 0x01400008 and w[2] >> 16 == 0x2409:
            table, number = '%02X' % (w[0] & 0xFFFF), w[2] & 0xFFFF
            name = NAMES[(table, number)]
            k = seen[name] = seen.get(name, 0) + 1
            sym = name if k == 1 else '%s_%d' % (name, k)
            lines += ['/* @%08X  %s(%02Xh) */' % (va, table[0], number),
                      'BIOS_TABLE_ENTRY(%s,%08X,0x%s,0x%02X);' % (sym, va, table, number)]
            funcs['%08X' % va] = sym
        elif w == [0x24040001, 0x0000000C, 0x03E00008, 0] or w == [0x24040002, 0x0000000C, 0x03E00008, 0]:
            sym = ('EnterCriticalSection', 'ExitCriticalSection')[w[0] & 0xFFFF == 2]
            lines += ['/* @%08X  syscall(%d) */' % (va, w[0] & 0xFFFF),
                      'BIOS_SYSCALL_ENTRY(%s,%08X,%d);' % (sym, va, w[0] & 0xFFFF)]
            funcs['%08X' % va] = sym
    (ROOT / 'src/semantic/bios_calls.c').write_text('\n'.join(lines) + '\n', newline='\n')

    names_path = ROOT / 'config/US/names.tsv'
    rows = {}
    if names_path.exists():
        rows = {r['va']: r for r in csv.DictReader(names_path.open(), delimiter='\t') if r['source'] != 'bios'}
    for va, sym in funcs.items():
        rows[va] = dict(va=va, name=sym, source='bios')
    with names_path.open('w', newline='\n') as f:
        f.write('va\tname\tsource\n')
        for va in sorted(rows):
            f.write('%s\t%s\t%s\n' % (va, rows[va]['name'], rows[va]['source']))
    print(json.dumps(dict(entries=len(funcs)), indent=None))
    return funcs


if __name__ == '__main__':
    main()
