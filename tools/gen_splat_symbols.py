#!/usr/bin/env python3
"""Write config/US/symbol_addrs.txt for splat from funcs.tsv (+ names.tsv).

Every discovered function start is declared with its size so splat and the
hybrid build agree on boundaries; names.tsv names replace func_XXXXXXXX.
Extra hand-written symbols can go in config/US/symbol_addrs_extra.txt.
"""
import csv
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def main():
    rows = list(csv.DictReader((ROOT / 'config/US/funcs.tsv').open(), delimiter='\t'))
    lines = ['// Generated by tools/gen_splat_symbols.py from config/US/funcs.tsv']
    for r in rows:
        va = int(r['va'], 16)
        lines.append('%s = 0x%08X; // type:func size:0x%X' % (r['name'], va, 4 * int(r['words'])))
    # Alternate entries (config/US/alt_entries.tsv) are not declared: spimdisasm
    # finds these jal targets itself and emits them as `alabel`s. Declaring
    # them only produces overlap warnings.
    extra = ROOT / 'config/US/symbol_addrs_extra.txt'
    if extra.exists():
        lines += ['', '// ---- symbol_addrs_extra.txt ----', extra.read_text().rstrip()]
    (ROOT / 'config/US/symbol_addrs.txt').write_text('\n'.join(lines) + '\n', newline='\n')
    print('%d function symbols' % len(rows))


if __name__ == '__main__':
    main()
